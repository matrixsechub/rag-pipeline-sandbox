if __name__ == "__main__":
    pipeline = RAGPipeline(
        docs_dir="data/sample_docs",
        chunk_strategy="recursive",
        chunk_size=300,
        chunk_overlap=50,
        top_k=3,
    )

    pipeline.build()

    queries = [
        "What is retrieval-augmented generation?",
        "Why is chunking important in RAG?",
        "How do embeddings enable semantic search?",
    ]

    for q in queries:
        print("\n" + "#"*60)
        response = pipeline.query(q)
        print(response)
