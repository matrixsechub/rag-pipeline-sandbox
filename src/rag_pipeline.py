
"""
rag_pipeline.py
---------------
End-to-end RAG pipeline that wires together:
  loading → chunking → embedding → storing → retrieving → generating

The LLM response generator is a PLACEHOLDER function.
It does not call any external API. It formats retrieved context
into a structured answer string to demonstrate grounding behavior.

To extend: replace `_placeholder_llm()` with a real LLM call
(e.g., Ollama, HuggingFace Transformers, OpenAI-compatible endpoint).
"""

import os
from pathlib import Path
from typing import List, Dict, Any, Optional

from src.chunking import chunk_text
from src.retrieval import VectorStore


# ---------------------------------------------------------------------------
# PLACEHOLDER LLM
# ---------------------------------------------------------------------------

def _placeholder_llm(query: str, context_chunks: List[str]) -> str:
    """
    Simulates a grounded LLM response using retrieved context.

    This is NOT a real language model. It demonstrates the RAG
    response format: show retrieved context + synthesize an answer.

    In a real system, replace this with:
        - Ollama (local Llama / Mistral / Phi)
        - HuggingFace `pipeline("text-generation", ...)`
        - Any OpenAI-compatible local endpoint

    Args:
        query:          The user's question.
        context_chunks: Top-K retrieved text chunks.

    Returns:
        A formatted response string grounded in the context.
    """
    if not context_chunks:
        return (
            "I could not find relevant context in the provided documents "
            "to answer your question. Please check the document collection "
            "or rephrase your query."
        )

    separator = "\n" + "-" * 40 + "\n"
    context_block = separator.join(
        f"[Source {i+1}]: {chunk}" for i, chunk in enumerate(context_chunks)
    )

    response = (
        f"QUERY: {query}\n\n"
        f"{'='*60}\n"
        f"RETRIEVED CONTEXT ({len(context_chunks)} chunks):\n"
        f"{'='*60}\n"
        f"{context_block}\n\n"
        f"{'='*60}\n"
        f"GROUNDED RESPONSE (placeholder):\n"
        f"{'='*60}\n"
        f"Based on the retrieved documents, here is a summary relevant to your query:\n\n"
    )

    # Simple extractive summary: first sentence of each chunk
    for i, chunk in enumerate(context_chunks):
        first_sentence = chunk.split(".")[0].strip()
        response += f"  • {first_sentence}.\n"

    response += (
        f"\n[NOTE] This response was generated by a placeholder function. "
        f"Replace `_placeholder_llm()` in rag_pipeline.py with a real "
        f"LLM for natural language generation."
    )

    return response


# ---------------------------------------------------------------------------
# RAG PIPELINE
# ---------------------------------------------------------------------------

class RAGPipeline:
    """
    Full RAG pipeline: load → chunk → embed → store → retrieve → generate.

    Args:
        docs_dir:        Path to directory containing .txt documents.
        chunk_strategy:  One of 'fixed', 'recursive', 'semantic'.
        chunk_size:      Max characters per chunk.
        chunk_overlap:   Overlap characters between chunks.
        top_k:           Number of chunks to retrieve per query.
        persist_dir:     Optional ChromaDB persistence directory.
        collection_name: ChromaDB collection name.

    Example:
        >>> pipeline = RAGPipeline("data/sample_docs")
        >>> pipeline.build()
        >>> answer = pipeline.query("What is RAG?")
        >>> print(answer)
    """

    def __init__(
        self,
        docs_dir: str = "data/sample_docs",
        chunk_strategy: str = "recursive",
        chunk_size: int = 300,
        chunk_overlap: int = 50,
        top_k: int = 3,
        persist_dir: Optional[str] = None,
        collection_name: str = "rag_sandbox",
    ):
        self.docs_dir = Path(docs_dir)
        self.chunk_strategy = chunk_strategy
        self.chunk_size = chunk_size
        self.chunk_overlap = chunk_overlap
        self.top_k = top_k

        self.store = VectorStore(
            collection_name=collection_name,
            persist_dir=persist_dir,
        )

        self._built = False

    # ------------------------------------------------------------------
    # STEP 1: LOAD DOCUMENTS
    # ------------------------------------------------------------------

    def load_documents(self) -> List[Dict[str, str]]:
        """
        Load all .txt files from docs_dir.

        Returns:
            List of dicts: {"filename": str, "content": str}
        """
        if not self.docs_dir.exists():
            raise FileNotFoundError(
                f"Document directory not found: {self.docs_dir}\n"
                f"Create it and add .txt files, or update the docs_dir parameter."
            )

        docs = []
        txt_files = sorted(self.docs_dir.glob("*.txt"))

        if not txt_files:
            raise ValueError(
                f"No .txt files found in {self.docs_dir}. "
                f"Add documents before building the pipeline."
            )

        for filepath in txt_files:
            content = filepath.read_text(encoding="utf-8").strip()
            if content:
                docs.append({"filename": filepath.name, "content": content})
                print(f"[pipeline] Loaded: {filepath.name} "
                      f"({len(content)} chars)")

        print(f"[pipeline] Total documents loaded: {len(docs)}")
        return docs

    # ------------------------------------------------------------------
    # STEP 2: CHUNK DOCUMENTS
    # ------------------------------------------------------------------

    def chunk_documents(
        self, documents: List[Dict[str, str]]
    ) -> List[Dict[str, Any]]:
        """
        Apply the configured chunking strategy to all documents.

        Returns:
            List of dicts: {"text": str, "source": str, "chunk_index": int}
        """
        all_chunks = []

        # Each strategy takes different keyword arguments; passing the union
        # raises TypeError. Semantic chunking sizes itself from paragraphs.
        strategy_kwargs = {
            "fixed": {"chunk_size": self.chunk_size, "overlap": self.chunk_overlap},
            "recursive": {"chunk_size": self.chunk_size, "chunk_overlap": self.chunk_overlap},
            "semantic": {},
        }.get(self.chunk_strategy, {})

        for doc in documents:
            chunks = chunk_text(
                doc["content"],
                strategy=self.chunk_strategy,
                **strategy_kwargs,
            )

            for i, chunk in enumerate(chunks):
                all_chunks.append({
                    "text": chunk,
                    "source": doc["filename"],
                    "chunk_index": i,
                })

        print(f"[pipeline] Total chunks created: {len(all_chunks)} "
              f"(strategy={self.chunk_strategy})")
        return all_chunks

    # ------------------------------------------------------------------
    # STEP 3 + 4: EMBED AND STORE
    # ------------------------------------------------------------------

    def embed_and_store(self, chunks: List[Dict[str, Any]]) -> None:
        """
        Embed all chunks and store them in ChromaDB.

        Embeddings are generated inside VectorStore.add_documents()
        via the embeddings module.

        Args:
            chunks: Output of chunk_documents().
        """
        texts = [c["text"] for c in chunks]
        metadatas = [
            {"source": c["source"], "chunk_index": c["chunk_index"]}
            for c in chunks
        ]
        ids = [
            f"{c['source']}_chunk_{c['chunk_index']}" for c in chunks
        ]

        self.store.add_documents(texts, metadatas=metadatas, ids=ids)

    # ------------------------------------------------------------------
    # BUILD: RUN STEPS 1–4
    # ------------------------------------------------------------------

    def build(self) -> None:
        """
        Execute the full ingestion pipeline:
          Load docs → Chunk → Embed → Store in ChromaDB.

        Call this once before querying.
        """
        print("\n" + "="*60)
        print(" RAG PIPELINE — BUILD PHASE")
        print("="*60)

        docs = self.load_documents()
        chunks = self.chunk_documents(docs)
        self.embed_and_store(chunks)

        self._built = True
        print("\n[pipeline] Build complete. Ready to query.")
        print("="*60 + "\n")

    # ------------------------------------------------------------------
    # STEP 5 + 6: RETRIEVE AND GENERATE
    # ------------------------------------------------------------------

    def query(self, question: str) -> str:
        """
        Run the full RAG query pipeline:
          Embed query → Retrieve top-K chunks → Generate response.

        Args:
            question: Natural language query string.

        Returns:
            A grounded response string (from placeholder LLM).

        Raises:
            RuntimeError: If build() has not been called first.
        """
        if not self._built:
            raise RuntimeError(
                "Pipeline not built. Call pipeline.build() before querying."
            )

        print(f"\n[pipeline] Query received: '{question}'")

        # Step 5: Retrieve
        results = self.store.query(question, top_k=self.top_k)

        if not results:
            return "No relevant documents found in the collection."

        context_chunks = [r["document"] for r in results]

        print(f"[pipeline] Retrieved {len(context_chunks)} chunks.")
        for r in results:
            print(f"  Rank {r['rank']} | Distance: {r['distance']} | "
                  f"Source: {r['metadata'].get('source', 'unknown')}")

        # Step 6: Generate
        response = _placeholder_llm(question, context_chunks)
        return response


